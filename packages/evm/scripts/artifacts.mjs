#!/usr/bin/env node
// Writes the EVM package's ABIs and creation bytecode from the contracts' own build (#252), so nothing about our
// contracts is ever typed by hand: `forge build` in contracts/, then `node packages/evm/scripts/artifacts.mjs`.
// With `--check` it writes nothing and fails when the committed files differ from what the build gives, which CI's
// contracts job runs after its own `forge build`, so a contract slice that changes an event fails until this is rerun.
/* global console, process */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..", "..");
const out = join(repo, "contracts", "out");
const generated = join(here, "..", "src", "generated");

/**
 * Every artifact the package carries: our contracts, and the two interfaces of other code the build compiles that the
 * Indexer reads (the PoolManager's `Swap` event, an ERC-20's metadata). `deploy` marks what the test stack deploys.
 */
const ARTIFACTS = [
  { name: "StokerFactory", deploy: true },
  { name: "StokerHook", deploy: true },
  { name: "StokerCoin" },
  { name: "QuoteRegistry", deploy: true },
  { name: "StokerKeys", deploy: true },
  { name: "IPoolManager" },
  { name: "IERC20Metadata" },
];

const camel = (name) => name[0].toLowerCase() + name.slice(1);
const HEADER = "// Generated by packages/evm/scripts/artifacts.mjs from `forge build` in contracts/ (#252). Do not edit: rerun the script.\n";

function read(name) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`${file} is missing: run \`forge build\` in contracts/ first (after ./script/deps.sh)`);
  const json = JSON.parse(readFileSync(file, "utf8"));
  return { abi: json.abi, bytecode: json.bytecode?.object };
}

const built = ARTIFACTS.map((a) => ({ ...a, ...read(a.name) }));
const abis =
  HEADER +
  built.map((a) => `\nexport const ${camel(a.name)}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n`).join("");
const bytecode =
  HEADER +
  "// The creation bytecode the test stack deploys; the API never imports it.\n" +
  built
    .filter((a) => a.deploy)
    .map((a) => {
      if (!/^0x[0-9a-f]+$/.test(a.bytecode)) throw new Error(`${a.name} has no creation bytecode in its artifact`);
      return `\nexport const ${camel(a.name)}Bytecode = "${a.bytecode}" as const;\n`;
    })
    .join("");

const files = { "abis.ts": abis, "bytecode.ts": bytecode };
if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([f, text]) => !existsSync(join(generated, f)) || readFileSync(join(generated, f), "utf8") !== text);
  if (stale.length) {
    console.error(`packages/evm/src/generated is not what the contracts build gives: ${stale.map(([f]) => f).join(", ")}.`);
    console.error("Run `node packages/evm/scripts/artifacts.mjs` after `forge build` in contracts/ and commit the result.");
    process.exit(1);
  }
  console.log("packages/evm/src/generated matches the contracts build.");
} else {
  for (const [f, text] of Object.entries(files)) writeFileSync(join(generated, f), text);
  console.log(`wrote ${Object.keys(files).map((f) => `packages/evm/src/generated/${f}`).join(" and ")}`);
}
